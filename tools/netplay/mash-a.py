#!/usr/bin/env python3
"""Writes tools/netplay/mash-a.script: tools/netplay/mash-a.py > tools/netplay/mash-a.script

The frames are tuned against GMPE01 Rev 1 from a FRESH user dir (no MemoryCardA.USA.raw: an existing
card takes another menu path; research/journal/2026-10-27-n15-determinism-run). Overlays reached, by
frame: boot 1, modesel 74 at 995, mentDll 70 at 1911 (party setup), w01 89 at 4182 (board), instDll 3
at 10579 (minigame instructions). It does not get into the minigame yet: the START window is before
instDll's intro ends. A change to a menu, or a different seed, moves these frames: rerun with
--hash-log and read hashdiff.py's overlays line.
"""

SEED = 0x50424E54
MENUS_END = 1900  # modesel is done by then; port 0 adds START to every 4th tap until here
INST_START = 10500  # instDll starts at 10579 (fresh user dir); it waits for START alone, after its intro
INST_END = 10800  # too early: the intro is still running (see the journal); START pauses a minigame
END = 13200


def main():
    out = ["# Generated by tools/netplay/mash-a.py; edit that and rerun it.",
           "#   partyboard --script tools/netplay/mash-a.script --hash-log run1.log",
           "#   partyboard --script tools/netplay/mash-a.script --hash-log run2.log",
           "#   tools/netplay/hashdiff.py run1.log run2.log",
           "# All four ports tap A (party setup waits for each player's own A; on the board all four are",
           "# human and roll). Port 0 adds START in the menus and taps START alone at the minigame",
           "# instructions (instDll leaves on START only).",
           f"seed 0x{SEED:08X}",
           f"end {END}"]
    f, i = 120, 0
    while f < END:
        in_inst = INST_START <= f < INST_END
        for p in range(4):
            if in_inst:
                b = "START" if p == 0 else "none"
            elif p == 0 and f < MENUS_END and i % 4 == 2:
                b = "A+START"
            else:
                b = "A"
            out.append(f"{f} {p} {b}")
        for p in range(4):
            out.append(f"{f + 5} {p} none")
        f += 60 if f < MENUS_END or in_inst else 30
        i += 1
    print("\n".join(out))


if __name__ == "__main__":
    main()
