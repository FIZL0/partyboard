#!/usr/bin/env python3
"""Writes the N30 save/continue scripts (research/journal/2026-10-27-n30-online-save-continue).

    tools/netplay/save-continue.py save     > save.script       # head: mash-a.script (title screen at 900)
    tools/netplay/save-continue.py title    > cont-title.script # head: mash-a.script
    tools/netplay/save-continue.py mgmode   > cont-mgmode.script # head: wander-mgmode.script (skipBootSequence)

    partyboard --script save.script --match 0@900 --hash-log save.log
        -> 'netplay: checkpoint at frame 9161, turn 1/10' and <user dir>/online/local-0000000050424E54.json
    partyboard --script cont-title.script  --continue <that json> --match 0@900 --hash-log a.log
    partyboard --script cont-mgmode.script --continue <that json> --match 0@900 --hash-log b.log
    tools/netplay/hashdiff.py --from 900 a.log b.log

Each script keeps its head's lines before frame 900 (the menu path to the match start) and then has the same pads:
port 0 taps A every 20 frames (the --match party has port 0 human, 1-3 CPU), and taps START alone inside the
window where instDll waits for it (main.c:295 wants exactly START; START outside it pauses a minigame or the
board). Frames are for GMPE01 Rev 1, fresh user dirs: save run instDll 6230, m4xx (ovl 14) 6507, resultDll
checkpoint 9161; continue runs instDll 5269, ovl 24 5547, checkpoint (turn 2/10) 8801.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MODES = {
    # mode: (head script, end frame, START window)
    "save": ("mash-a.script", 14000, (6300, 6510)),
    "title": ("mash-a.script", 20000, (5340, 5550)),
    "mgmode": ("wander-mgmode.script", 20000, (5340, 5550)),
}
MATCH_AT = 900


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in MODES:
        sys.exit(f"usage: {sys.argv[0]} {'|'.join(MODES)}")
    head, end, (lo, hi) = MODES[sys.argv[1]]
    out = [f"# Generated by tools/netplay/save-continue.py {sys.argv[1]}; edit that and rerun it."]
    with open(os.path.join(HERE, head)) as f:
        for line in f:
            p = line.split()
            if not p or p[0].startswith("#") or p[0] == "end":
                continue
            if p[0] == "seed" or int(p[0]) < MATCH_AT:
                out.append(line.strip())
    out.append(f"end {end}")
    out += [f"{MATCH_AT} {p} none" for p in range(1, 4)]
    for f in range(MATCH_AT, end, 20):
        out += [f"{f} 0 {'START' if lo <= f < hi else 'A'}", f"{f + 5} 0 none"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
