#!/usr/bin/env python3
"""Writes tools/netplay/party.script: tools/netplay/party.py > tools/netplay/party.script

A whole --match party for tools/netplay/party_check.sh (N53): two runs of the same build and pads must give the
same hash log. Run it with `--match 0@1500 --turbo`. Up to MATCH_AT the pads are mash-a.script's (boot to
modeseldll); from there all four ports tap A every TAP frames. The script needs no tuning to the party's frames:
- `mg-explain off`: no minigame explanations, so instDll needs no START alone;
- `ovl 78 1 <port> START`: the party results (mstory3Dll, ovl 78, event 1) get START alone on every port. They read
  the pad of the player they show (fn_1_16924), leave on START and turn pages on A; START after an A is lost in the
  page animation. Event 0 (the ceremony before them) needs A. The match is then over (netplay: match over), back in
  modeseldll.
- `lottery-stick on`: the lottery's ball game and ticket scratch get the script's stick for a human current player
  (N79): A taps alone leave the party in them forever (since N69's party buys a ticket in turn 8).
GMPE01 Rev 1, fresh user dir, at N53: board w01 from 1502, 13 minigames, turn 10 ends at ~115500 (mstory3), the match
is over at ~121000. A change to the game moves these frames; the check only needs both runs to agree.
"""

SEED = 0x50424E54
MATCH_AT = 1500  # --match 0@1500
MENUS_END = 1900  # mash-a.py: port 0 adds START to every 4th tap until here
TAP = 20
END = 135000


def main():
    out = ["# Generated by tools/netplay/party.py; edit that and rerun it.",
           "#   tools/netplay/party_check.sh   (two runs with --match 0@1500 --turbo, then hashdiff.py)",
           f"seed 0x{SEED:08X}",
           f"end {END}",
           "mg-explain off",
           "lottery-stick on"]
    out += [f"ovl 78 1 {p} START" for p in range(4)]
    f, i = 120, 0
    while f < MATCH_AT:
        for p in range(4):
            b = "A+START" if p == 0 and f < MENUS_END and i % 4 == 2 else "A"
            out.append(f"{f} {p} {b}")
        for p in range(4):
            out.append(f"{f + 5} {p} none")
        f += 60
        i += 1
    f = MATCH_AT
    while f < END:
        for p in range(4):
            out.append(f"{f} {p} A")
        for p in range(4):
            out.append(f"{f + 5} {p} none")
        f += TAP
    print("\n".join(out))


if __name__ == "__main__":
    main()
